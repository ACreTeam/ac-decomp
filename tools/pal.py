def configure_sources(config):
    catalog = []
    for lib in config.libs:
        for obj in lib["objects"]:
            options = {k: v for k, v in lib.items() if k != "objects"}
            options.update({k: v for k, v in obj.options.items() if v is not None})
            path = Path(options.get("src_dir") or config.src_dir) / options["source"]
            if path.is_file():
                catalog.append((obj.name, path, options))

    # OSExec was added to this SDK but is unused in the Australian build.
    os_options = next(o for _, p, o in catalog if p.name == "OS.c")
    catalog.append(("OSExec.c", Path("src/static/dolphin/2.6/src/os/OSExec.c"), os_options))
    # e+ introduced these TUs before the PAL fork; their copies live in PAL.
    for name, source, library in (
        ("reload_data.o", "src/PAL/reload_data.c", "foresta"),
        ("isterminatedthread.c", "src/PAL/static/libultra/isterminatedthread.c", "libultra"),
    ):
        options = next(o for _, _, o in catalog if o.get("lib") == library)
        catalog.append((name, Path(source), options))
    by_stem = {}
    for candidate in catalog:
        by_stem.setdefault(_stem(candidate[0]), []).append(candidate)
    paths = [Path(config.config_path).with_name("splits.txt")]
    paths += [Path(config.config_path).parent / module / "splits.txt"
              for module in ("foresta", "forestd", "foresti", "foresto")]
    objects = {}
    for splits in paths:
        for name in re.findall(r"^([^\s#][^:]*):", splits.read_text(), re.MULTILINE):
            if name == "Sections" or name in objects:
                continue
            candidates = by_stem.get(_stem(name), [])
            if name == "data/model/log_win_nintendo1_tex.c":
                candidates = by_stem.get("logo_nin_copy", candidates)
            if name.startswith("data/") or name.startswith("bootdata/"):
                candidates = [c for c in candidates if c[0] == name or (name == "data/model/log_win_nintendo1_tex.c" and c[0] == "data/model/logo_nin_copy.c")]
            elif "/" in name:
                archive = name.split("/")[0].lower().removesuffix(".a")
                if archive == "gba2":
                    candidates = [c for c in candidates if c[2].get("lib") == "boot"]
                elif archive.startswith("jaudio_"):
                    candidates = [c for c in candidates if str(c[2].get("lib", "")).startswith("jaudio_")]
                else:
                    candidates = [c for c in candidates if str(c[2].get("lib", "")).lower() == archive]
            else:
                candidates = [c for c in candidates if "/data/" not in c[1].as_posix()]
            candidates = {p: (n, p, o) for n, p, o in candidates}
            if len(candidates) > 1:
                aus = {p: c for p, c in candidates.items() if "AUS" in p.parts}
                if aus:
                    candidates = aus
            if not candidates:
                continue  # PAL-only TUs retain their original objects.
            if len(candidates) != 1:
                raise ValueError(f"Ambiguous PAL source for {name}: {list(candidates)}")
            _, source, options = next(iter(candidates.values()))
            relative = source.relative_to("src")
            if relative.parts[0] in ("AUS", "PAL"):
                relative = Path(*relative.parts[1:])
            source = next((p for p in (Path("src/PAL") / relative, Path("src/AUS") / relative, source)
                           if p.is_file()), source)
            options = dict(options)
            options.update(src_dir=".", source=source.as_posix(), mw_version="GC/2.6")
            module_include = [] if splits == paths[0] else [
                f"-i {config.out_path().as_posix()}/include/{splits.parent.name}"
            ]
            # PAL mirrors the base tree and overrides shared Australian/US headers.
            pal_includes = ["-i include/PAL", "-i include/PAL/dolphin", "-i src/PAL/static"]
            options["cflags"] = [
                *pal_includes, *module_include,
                *[f for f in options["cflags"] if f not in pal_includes],
            ]
            # Boot's PAL implementation and flags have passed all five linked builds.
            language = config.version.rsplit("_", 1)[1]
            pending = language in LANGUAGE_PENDING_PORTS.get(name, set())
            options["add_to_all"] = name not in PENDING_PORTS and not pending
            options["objdiff"] = options["add_to_all"]
            boot_matching = name == "boot.o" and source == Path("src/PAL/static/boot.c")
            matching = (
                boot_matching
                or name in MATCHING_ADDITIONAL
                or (splits.parent.name == "foresta" and name in MATCHING_FORESTA)
            )
            if boot_matching:
                options["extra_cflags"] = ["-inline on"]
            objects[name] = Object(matching, name, **options)
    config.libs = [{"lib": "pal", "objects": list(objects.values())}]
    config.reconfig_deps = [*(config.reconfig_deps or []), *paths]
